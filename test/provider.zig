//! Names the native provider a test run needs, and fails when there is none.
//!
//! ## Why this file exists
//!
//! The same four test files run in both configurations.  In a linked build
//! the C library is in the binary and every test works with no setup.  In a
//! runtime-loading build (`-Druntime=true`) nothing is linked, every codec
//! call goes through a table, and that table is empty until somebody loads
//! a provider.  A test suite that quietly passed without one would be
//! asserting nothing at all, so in that configuration every test loads
//! explicitly and a run that was not told which provider to use fails.
//!
//! ## What is read, and what is not
//!
//! `HTSCODECS_PROVIDER`, and nothing else.  There is no default location, no
//! search path, no fallback to a system library, and no path-to-system
//! fallback inside the loader either.  `export HTSCODECS_PROVIDER=/path/to/
//! libhtscodecs.so` before `zig build test`, or let the build pass the
//! variable to the run step; both work because a run step inherits the
//! environment it was started from.
//!
//! An absolute path is what should be named.  The loader hands the string to
//! the platform loader unchanged and adds no search of its own, so a
//! relative path means whatever the platform means by one; if it does not
//! open, `load` reports `OpenFailed` and the platform's own diagnosis is
//! what you get.
//!
//! ## The `getenv` declaration
//!
//! A Zig test binary has no `std.process.Init` to read an environment from -
//! that is a `main` parameter, and a test's `main` is generated by the test
//! runner.  `std.c.getenv` has the same problem: it is only compiled in
//! where `std.c` itself is.  Declaring the one C function here is exact for
//! every target these tests are built for, all of which link libc, and it is
//! an ordinary C import in a test file rather than anything routed, so it
//! has no bearing on the dispatch the package generates.

const std = @import("std");
const htscodecs = @import("htscodecs");

/// The environment variable naming the provider file.
pub const variable = "HTSCODECS_PROVIDER";

extern "c" fn getenv(name: [*:0]const u8) ?[*:0]u8;

/// What this file can add to what `load` can already say.
pub const Problem = error{
    /// A runtime-loading build was not told which provider to use.  Reported
    /// with the variable's name, because an error name on its own would send
    /// the next person into the loader instead of to their shell.
    NoProviderConfigured,
};

/// Makes this process's codec calls work, in whichever configuration this
/// build is.
///
/// A linked build returns immediately: the library is already in the binary
/// and there is nothing to load.  A runtime-loading build loads the provider
/// named by `HTSCODECS_PROVIDER`, or fails.
///
/// Call this before the first codec call in every test.  A call before a
/// successful load is a panic naming the function, in every optimisation
/// mode, so a test that forgets is loud rather than subtly wrong.
pub fn load() (htscodecs.LoadError || Problem)!void {
    // A linked build has the library in the binary and there is nothing to
    // load.
    //
    // The whole runtime-only body sits inside a comptime-known branch, and
    // that is not tidiness.  In a linked build `c` is the translated header
    // and has no `load` at all - only the generated dispatch declares one -
    // so a reference to it anywhere outside a dropped branch would be a
    // compile error in exactly the configuration that needs this file most
    // to be harmless.
    if (comptime htscodecs.runtime_loaded) {
        // Calling this twice in one process is harmless: `load` is idempotent
        // for the same request and refuses a different one, so the second
        // call either does nothing or reports `ProviderMismatch`; either way
        // the library in use does not change.  The early return short-
        // circuits the common case of several tests sharing one process.
        if (htscodecs.loadedSource() != null) return;

        const raw = getenv(variable) orelse {
            std.debug.print(
                "htscodecs tests: this is a runtime-loading build, so nothing " ++
                    "is linked and every codec call needs a provider first. " ++
                    "Export {s} with the shared object to load and run the " ++
                    "tests again. No other file is tried, and a test that " ++
                    "cannot name a provider is a failure rather than a " ++
                    "pass.\n",
                .{variable},
            );
            return error.NoProviderConfigured;
        };

        try htscodecs.load(.{ .path = std.mem.span(raw) });
    }
}
